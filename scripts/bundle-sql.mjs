// Joins supabase/migrations/*.sql into supabase/setup.sql so a new project can be set up
// with one paste in the Supabase SQL Editor. Run after changing a migration:
//   node scripts/bundle-sql.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const parts = files.map((f) => `-- =====================================================================\n-- ${f}\n-- =====================================================================\n\n${readFileSync(join(dir, f), "utf8").trim()}\n`);
const head = `-- SalesDesk: the whole database in one file, for a NEW Supabase project.
-- Paste everything into the SQL Editor and press Run once.
-- Generated by scripts/bundle-sql.mjs from supabase/migrations/ — do not edit this file.
-- A project that already ran some migrations runs only the newer files from supabase/migrations/.

`;
writeFileSync("supabase/setup.sql", head + parts.join("\n"));
console.log(`supabase/setup.sql written from ${files.length} files`);
